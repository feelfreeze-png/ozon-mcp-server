class LimitExceeded(ValueError):
    """Запрос сверх лимита. Отвергнут нами, а не Ozon."""


def limit(key: str) -> Limit:
    try:
        return LIMITS[key]
    except KeyError:
        raise KeyError(
            f"лимит {key!r} не заведён. Числа лимитов живут одним местом — "
            "в ozon_mcp/limits.py, с пометкой происхождения."
        ) from None


def check(key: str, items: Sequence[T]) -> Sequence[T]:
    """Отвергнуть запрос сверх лимита, назвав число и его происхождение."""
    known = limit(key)
    if len(items) > known.value:
        raise LimitExceeded(
            f"{len(items)} > {known.value}: {known.what}. "
            f"Происхождение числа — {known.origin} ({known.evidence}). "
            "Запрос отвергнут до отправки: ответ Ozon сверх лимита бывает неотличим "
            "от пустого результата."
        )
    return items


def chunks(key: str, items: Sequence[T]) -> Iterator[list[T]]:
    """Разбить на порции по лимиту. Пустой вход не даёт ни одной порции."""
    size = limit(key).value
    for start in range(0, len(items), size):
        yield list(items[start:start + size])


def unverified() -> list[str]:
    """Лимиты, на которые мы опираемся, не замерив. Для отчёта, а не для украшения."""
    return sorted(key for key, value in LIMITS.items() if not value.verified)


# ── Единицы бюджета: замер отложен решением владельца ────────────────────────

class UnmeasuredUnitError(RuntimeError):
    """Величину просят преобразовать в единицу, которая не замерена."""


#: Переменная, которой замер объявляется выполненным. Значение — множитель:
#: сколько единиц Ozon в одном рубле. Допустимы только два кандидата — те, между
#: которыми чтение не различило.
BUDGET_UNIT_ENV = "OZON_BUDGET_UNIT_PER_RUB"

_BUDGET_CANDIDATES = (1_000_000, 1_000_000_000)


def budget_to_api(rub: float, *, field: str) -> str:
    """Рубли → единицы Ozon. Отказ, пока единица не замерена.

    🔴 **Решение владельца 21.09.2026: замер единиц бюджета отложен до этапа 2** и
    становится его первым действием. Чтением вопрос не решается — доводы разобраны в
    `docs/UNITS-bids-budgets.md`; нужна одна запись известного значения с чтением
    обратно.

    Отсюда и эта функция. Отложить замер, оставив в коде молчаливое `* 1_000_000`,
    значило бы отложить не вопрос, а его последствие: ошибка в единице бюджета в тысячу
    раз ничем не отличается от верной настройки, кроме счёта в конце недели. Ставки —
    другое дело: они замерены двумя источниками и микрорублёвые. Речь только о бюджетах.

    После замера: выставить `OZON_BUDGET_UNIT_PER_RUB` равным измеренному множителю и
    переписать этот докстринг на запись о замере.
    """
    raw = (os.environ.get(BUDGET_UNIT_ENV) or "").strip()
    if not raw:
        raise UnmeasuredUnitError(
            f"{field}: единица бюджета не замерена, преобразование из рублей запрещено. "
            f"Чтение вопрос не решает: 44 разных значения weeklyBudget одинаково "
            f"правдоподобны и как микрорубли, и как ÷10⁹, а потолка ни одна кампания не "
            f"достигала. Решает одна запись: выставить кампании заведомо известный "
            f"бюджет (например 1234 ₽) и прочитать обратно — 1234000000 значит "
            f"микрорубли, 1234000000000 значит ÷10⁹. Замер отложен решением владельца до "
            f"этапа 2 и является его ПЕРВЫМ действием; до него выставлять "
            f"{BUDGET_UNIT_ENV} нельзя: переменная объявляет замер выполненным, а не "
            f"заменяет его."
        )
    try:
        factor = int(raw)
    except ValueError:
        raise UnmeasuredUnitError(
            f"{BUDGET_UNIT_ENV}={raw!r} — не целое число. Ожидается множитель: сколько "
            f"единиц Ozon в одном рубле."
        ) from None
    if factor not in _BUDGET_CANDIDATES:
        raise UnmeasuredUnitError(
            f"{BUDGET_UNIT_ENV}={factor} не входит в число кандидатов "
            f"{_BUDGET_CANDIDATES}. Замер обязан дать один из них; другое значение "
            f"означает опечатку, а опечатка здесь стоит порядка."
        )
    return str(int(rub * factor))
